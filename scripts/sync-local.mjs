#!/usr/bin/env node
/**
 * Vendors the local edition's packages into the CLI, so `clipy --local` works
 * from the standalone @clipy/cli package with no workspace dependencies.
 *
 * Source: oss/packages/{moments,config,capture,transcribe}/src (Apache-2.0),
 * after oss/scripts/sync-from-monorepo.mjs has generated the files those
 * packages copy from lib/. Destination: cli/src/local/vendor/<pkg>/, which is
 * gitignored here and rewritten on every build, the same way
 * sync-context-core.mjs handles lib/context-core.
 *
 * Every copy gets an SPDX header (the CLI itself is MIT; these files stay
 * Apache-2.0, see LICENSE-APACHE) and a GENERATED line, and its cross-package
 * imports (`@clipy/moments`) become relative paths.
 *
 * Publishing from the standalone mirror repo: oss/ is not there, but the
 * vendored copy in src/ is, so nothing is synced.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, posix, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const oss = join(here, "..", "..", "oss");
const packagesDir = join(oss, "packages");
const dest = join(here, "..", "src", "local", "vendor");

/** oss package folder -> the package name other packages import it by. */
const PACKAGES = {
  moments: "@clipy/moments",
  config: "@clipy/local-config",
  capture: "@clipy/capture",
  transcribe: "@clipy/transcribe",
};

if (!existsSync(join(packagesDir, "moments", "src", "index.ts"))) {
  process.stderr.write("[sync-local] oss/packages not found, keeping the existing vendored copy\n");
  process.exit(0);
}

// The moments package copies its detectors and planner from lib/; make sure
// those generated files exist and are current before vendoring them.
const monorepoSync = join(oss, "scripts", "sync-from-monorepo.mjs");
if (existsSync(monorepoSync)) {
  execFileSync(process.execPath, [monorepoSync], { stdio: ["ignore", "ignore", "inherit"] });
}

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (name.endsWith(".ts") && !name.endsWith(".d.ts")) out.push(full);
  }
  return out;
}

const toPosix = (p) => p.split(sep).join(posix.sep);

function rewrite(source, fileDestDir, file) {
  let out = source.replace(/(from\s+['"]|import\(\s*['"])(@clipy\/[a-z-]+)(['"])/g, (_m, pre, spec, post) => {
    const pkg = Object.entries(PACKAGES).find(([, name]) => name === spec)?.[0];
    if (!pkg) throw new Error(`${file}: unknown package import ${spec}`);
    let rel = toPosix(relative(fileDestDir, join(dest, pkg, "index.js")));
    if (!rel.startsWith(".")) rel = `./${rel}`;
    return `${pre}${rel}${post}`;
  });
  // NodeNext ESM needs explicit extensions on relative imports.
  out = out.replace(/(from\s+['"]\.\.?\/[^'"]+?)(['"])/g, (_m, path, quote) =>
    path.endsWith(".js") || path.endsWith(".json") ? `${path}${quote}` : `${path}.js${quote}`,
  );
  return out;
}

rmSync(dest, { recursive: true, force: true });
let count = 0;
for (const pkg of Object.keys(PACKAGES)) {
  const srcRoot = join(packagesDir, pkg, "src");
  for (const file of walk(srcRoot)) {
    const relPath = relative(srcRoot, file);
    const target = join(dest, pkg, relPath);
    mkdirSync(dirname(target), { recursive: true });
    const header =
      "// SPDX-License-Identifier: Apache-2.0\n" +
      `// GENERATED from oss/packages/${pkg}/src/${toPosix(relPath)} by cli/scripts/sync-local.mjs. Do not edit here.\n`;
    writeFileSync(target, header + rewrite(readFileSync(file, "utf8"), dirname(target), file));
    count++;
  }
}

writeFileSync(
  join(dest, "README.md"),
  "# Vendored local edition packages\n\n" +
    "Generated by `cli/scripts/sync-local.mjs` from `oss/packages/*/src` in the Clipy monorepo. " +
    "These files are licensed under the Apache License 2.0 (see `LICENSE-APACHE` in the package root), " +
    "not the MIT license that covers the rest of the CLI. Do not edit them here.\n",
);

process.stdout.write(`[sync-local] vendored ${count} files into src/local/vendor\n`);
